import { Activity } from "lucide-react";
import DashboardCard from "../common/DashboardCard";

function PredictionSummary({
  disease,
  confidence,
}) {
  const hasPrediction =
    disease && confidence !== undefined && confidence !== null;

  const confidenceValue = hasPrediction
    ? Math.max(0, Math.min(100, Number(confidence)))
    : 0;

  return (
    <DashboardCard>

      {/* ======================================
          HEADER
      ====================================== */}

      <div className="flex items-start justify-between">

        <div>

          <p
            className="
              text-[10px]
              font-medium
              uppercase
              tracking-[0.25em]
              text-neutral-600
            "
          >
            YOUR RESULT
          </p>

          <h2
            className="
              mt-2
              text-lg
              font-semibold
              tracking-[-0.025em]
              text-white
            "
          >
            AI-assisted assessment
          </h2>

        </div>


        <div
          className="
            flex
            h-9
            w-9
            items-center
            justify-center
            rounded-full
            border
            border-white/[0.10]
            bg-white/[0.025]
          "
        >
          <Activity
            className="h-4 w-4 text-neutral-400"
            strokeWidth={1.5}
          />
        </div>

      </div>


      {/* ======================================
          PREDICTION
      ====================================== */}

      <div className="mt-8">

        <p className="text-xs text-neutral-600">
          Most probable condition
        </p>

        <h3
          className="
            mt-2
            text-3xl
            font-semibold
            leading-tight
            tracking-[-0.04em]
            text-white
            sm:text-4xl
          "
        >
          {disease || "Waiting for analysis"}
        </h3>

      </div>


      {/* ======================================
          CONFIDENCE
      ====================================== */}

      <div className="mt-8">

        <div className="flex items-center justify-between">

          <span className="text-xs text-neutral-500">
            Model confidence
          </span>

          <span className="text-sm font-medium text-neutral-300">
            {hasPrediction
              ? `${confidenceValue}%`
              : "--"}
          </span>

        </div>


        <div
          className="
            mt-3
            h-1.5
            overflow-hidden
            rounded-full
            bg-white/[0.08]
          "
        >

          <div
            className="
              h-full
              rounded-full
              bg-white
              transition-all
              duration-700
            "
            style={{
              width: `${confidenceValue}%`,
            }}
          />

        </div>

      </div>


      {/* ======================================
          EMPTY / DISCLAIMER
      ====================================== */}

      {!hasPrediction ? (

        <p
          className="
            mt-6
            border-t
            border-white/[0.07]
            pt-5
            text-xs
            leading-5
            text-neutral-600
          "
        >
          Select at least three symptoms and analyse them
          to generate a result.
        </p>

      ) : (

        <p
          className="
            mt-6
            border-t
            border-white/[0.07]
            pt-5
            text-[11px]
            leading-5
            text-neutral-600
          "
        >
          This result is generated by a machine learning model
          and is intended for informational purposes only. It
          does not constitute a medical diagnosis.
        </p>

      )}

    </DashboardCard>
  );
}

export default PredictionSummary;